import AppKit
import ApplicationServices
import Combine
import ImageIO
import UniformTypeIdentifiers

/// Watches the general pasteboard. macOS has no change notification, so it
/// checks `changeCount` twice a second, which is cheap.
final class ClipboardService: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    /// Card to flash a "Copied/Pasted ✓" confirmation on.
    @Published private(set) var flashedID: UUID?
    @Published private(set) var lastActionWasPaste = false

    /// Feature flag. Starts off; the app enables it after the launch greeting.
    /// When off, the clipboard isn't watched and history is cleared.
    var isEnabled = false {
        didSet {
            guard isEnabled != oldValue else { return }
            // Never record what was copied while the feature was off.
            lastChangeCount = pasteboard.changeCount
            if isEnabled { loadPins() } else { items.removeAll() }
        }
    }

    /// Paused while the Mac is locked.
    var isPaused = false

    /// Fires when the user copies something new (not when we write ourselves).
    let copied = PassthroughSubject<ClipItem, Never>()

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var ownChangeCount: Int?
    private var timer: Timer?
    private var flashWork: DispatchWorkItem?
    private var askedForAccessibility = false
    private let maxItems = 8

    /// Markers password managers and other apps set for data that must not be recorded.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
        // Generous tolerance lets macOS bundle this with its other wake-ups (saves battery).
        timer.tolerance = 0.3
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    deinit { timer?.invalidate() }

    // MARK: - Actions

    /// Puts an item back on the clipboard and moves it to the front.
    func copy(_ item: ClipItem) {
        write(item)
        flash(item, pasted: false)
    }

    /// Copies, then sends ⌘V to the frontmost app. Returns false (copy only)
    /// when Accessibility permission hasn't been granted yet.
    @discardableResult
    func paste(_ item: ClipItem) -> Bool {
        write(item)
        guard hasAccessibility() else {
            flash(item, pasted: false)
            return false
        }
        flash(item, pasted: true)
        // Give the island a moment to collapse; our panel never takes focus,
        // so the keystroke lands in the app the user was working in.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            Self.postCommandV()
        }
        return true
    }

    /// Adds a file to the history without touching the pasteboard (screenshots, downloads).
    @discardableResult
    func addShelfFile(_ url: URL, source: String, icon: NSImage?) -> ClipItem {
        let content = ClipItem.Content.files([url])
        let item = ClipItem(content: content, thumbnail: Self.thumbnail(for: content), sourceApp: source, sourceIcon: icon)
        if isEnabled { insert(item) }
        return item
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        var updated = items.remove(at: index)
        updated.isPinned.toggle()
        insert(updated)
        savePins()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        if item.isPinned { savePins() }
    }

    /// Clears the history; pinned items stay.
    func clearUnpinned() {
        items.removeAll { !$0.isPinned }
    }

    var hasUnpinned: Bool { items.contains { !$0.isPinned } }

    // MARK: - Internals

    private func write(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let string):
            pasteboard.setString(string, forType: .string)
        case .image(let image):
            pasteboard.writeObjects([image])
        case .files(let urls):
            pasteboard.writeObjects(urls.map { $0 as NSURL })
        }
        ownChangeCount = pasteboard.changeCount
        // Re-using an unpinned item moves it to the front of the history.
        if let index = items.firstIndex(where: { $0.id == item.id }), !items[index].isPinned {
            var moved = items.remove(at: index)
            moved.date = Date()
            insert(moved)
        }
    }

    /// Pinned first (in pin order), then history newest-first, capped at `maxItems`.
    private func insert(_ item: ClipItem) {
        if item.isPinned {
            let lastPinned = items.lastIndex { $0.isPinned }.map { $0 + 1 } ?? 0
            items.insert(item, at: lastPinned)
        } else {
            let firstUnpinned = items.firstIndex { !$0.isPinned } ?? items.count
            items.insert(item, at: firstUnpinned)
        }
        let unpinned = items.indices.filter { !items[$0].isPinned }
        if unpinned.count > maxItems {
            for index in unpinned.suffix(unpinned.count - maxItems).reversed() {
                items.remove(at: index)
            }
        }
    }

    // MARK: - Pins (text only, kept in UserDefaults)

    private static let pinsKey = "clipboard.pinned"

    private func savePins() {
        let texts = items.filter(\.isPinned).compactMap(\.text)
        UserDefaults.standard.set(texts, forKey: Self.pinsKey)
    }

    private func loadPins() {
        let texts = UserDefaults.standard.stringArray(forKey: Self.pinsKey) ?? []
        let existing = Set(items.filter(\.isPinned).compactMap(\.text))
        for text in texts where !existing.contains(text) {
            insert(ClipItem(content: .text(text), thumbnail: nil, isPinned: true))
        }
    }

    private func flash(_ item: ClipItem, pasted: Bool) {
        flashWork?.cancel()
        lastActionWasPaste = pasted
        flashedID = item.id
        let work = DispatchWorkItem { [weak self] in self?.flashedID = nil }
        flashWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2, execute: work)
    }

    /// Asks macOS once (shows the system prompt), then just checks.
    private func hasAccessibility() -> Bool {
        let prompt = !askedForAccessibility
        askedForAccessibility = true
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        return AXIsProcessTrustedWithOptions([key: prompt] as CFDictionary)
    }

    private static func postCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 0x09
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        down?.flags = .maskCommand
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    private var pollTick = 0

    private func poll() {
        // Low Power Mode: check once a second instead of twice.
        pollTick &+= 1
        if Energy.saver && ProcessInfo.processInfo.isLowPowerModeEnabled && pollTick % 2 == 1 { return }
        guard isEnabled, !isPaused else { return }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard count != ownChangeCount else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes), let content = readContent() else { return }

        if case .text(let newText) = content {
            // Already pinned → nothing new to remember.
            if items.contains(where: { $0.isPinned && $0.text == newText }) { return }
            items.removeAll { !$0.isPinned && $0.text == newText }
        }
        let source = NSWorkspace.shared.frontmostApplication
        let item = ClipItem(
            content: content,
            thumbnail: Self.thumbnail(for: content),
            sourceApp: source?.localizedName,
            sourceIcon: source?.icon
        )
        insert(item)
        copied.send(item)
    }

    private func readContent() -> ClipItem.Content? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls)
        }
        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(string)
        }
        if let image = NSImage(pasteboard: pasteboard) {
            return .image(image)
        }
        return nil
    }

    // MARK: - Thumbnails

    static func thumbnail(for content: ClipItem.Content) -> NSImage? {
        switch content {
        case .text:
            return nil
        case .image(let image):
            guard let data = image.tiffRepresentation,
                  let source = CGImageSourceCreateWithData(data as CFData, nil)
            else { return image }
            return downsample(source) ?? image
        case .files(let urls):
            guard urls.count == 1,
                  let type = UTType(filenameExtension: urls[0].pathExtension),
                  type.conforms(to: .image),
                  let source = CGImageSourceCreateWithURL(urls[0] as CFURL, nil)
            else { return nil }
            return downsample(source)
        }
    }

    private static func downsample(_ source: CGImageSource) -> NSImage? {
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 320,
        ]
        guard let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSImage(cgImage: cgImage, size: .zero)
    }
}
